package daemon

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

var updateIssueTimezones = flag.Bool("update-golden", false, "refresh issue timezone inventory from the Go toolchain bundle")

func TestIssuePortableTimezoneInventory(t *testing.T) {
	toolchain, err := exec.CommandContext(t.Context(), "go", "env", "GOROOT", "GOVERSION").Output()
	require.NoError(t, err)
	root, goVersion, _ := strings.Cut(strings.TrimSpace(string(toolchain)), "\n")
	bundle := filepath.Join(root, "lib", "time", "zoneinfo.zip")
	data, err := os.ReadFile(bundle)
	require.NoError(t, err, "toolchain timezone ZIP is required")
	archive, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	require.NoError(t, err)
	names := []string{"UTC", "Etc/UTC"}
	for _, file := range archive.File {
		area, _, _ := strings.Cut(file.Name, "/")
		if slices.Contains([]string{"Africa", "America", "Antarctica", "Arctic", "Asia", "Atlantic", "Australia", "Europe", "Indian", "Pacific"}, area) && !file.FileInfo().IsDir() {
			names = append(names, file.Name)
		}
	}
	slices.Sort(names)
	names = slices.Compact(names)
	var content strings.Builder
	fmt.Fprintf(&content, "// Code generated by TestIssuePortableTimezoneInventory -update-golden; DO NOT EDIT.\n// Source: %s lib/time/zoneinfo.zip (geographic aliases included).\n// Bundle SHA-256: %x\n\npackage daemon\n\nvar portableIssueTimezones = [...]string{\n", goVersion, sha256.Sum256(data))
	for chunk := range slices.Chunk(names, 4) {
		quoted := make([]string, len(chunk))
		for i, name := range chunk {
			quoted[i] = fmt.Sprintf("%q,", name)
		}
		fmt.Fprintf(&content, "\t%s\n", strings.Join(quoted, " "))
	}
	content.WriteString("}\n")
	const target = "issue_timezones_gen.go"
	if *updateIssueTimezones {
		require.NoError(t, os.WriteFile(target, []byte(content.String()), 0644))
	}
	committed, err := os.ReadFile(target)
	require.NoError(t, err)
	require.Equal(t, content.String(), string(committed), "refresh with go test ./internal/daemon -run '^TestIssuePortableTimezoneInventory$' -update-golden")
	t.Logf("checked %d bundled names", len(names))
}
