// Command gentzindex indexes the timezone names bundled with the Go toolchain.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatal(err)
	}
	archive, err := zip.OpenReader(filepath.Join(strings.TrimSpace(string(goroot)), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = archive.Close() }()
	names := make([]string, 0, len(archive.File))
	for _, file := range archive.File {
		names = append(names, file.Name)
	}
	slices.Sort(names)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate ./internal/cron; DO NOT EDIT.")
	fmt.Fprintln(&out, "\npackage cron\n\nvar bundledZones = map[string]struct{}{")
	for _, name := range names {
		fmt.Fprintf(&out, "\t%q: {},\n", name)
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tzindex_gen.go", formatted, 0o600); err != nil {
		log.Fatal(err)
	}
}
