#!/usr/bin/env python3
"""Refresh/check issue timezone admission names from Go 1.27.3's bundle.

Usage: python3 scripts/update-issue-timezones.py /path/to/go/lib/time/zoneinfo.zip [--check]
Run with the pinned toolchain; no system timezone files are consulted.
"""

import argparse
import hashlib
from pathlib import Path
import zipfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("bundle", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
regions = {
    "Africa", "America", "Antarctica", "Arctic", "Asia", "Atlantic",
    "Australia", "Europe", "Indian", "Pacific",
}
with zipfile.ZipFile(args.bundle) as archive:
    names = sorted({"UTC", "Etc/UTC"} | {
        name for name in archive.namelist()
        if name.partition("/")[0] in regions and not name.endswith("/")
    })
digest = hashlib.sha256(args.bundle.read_bytes()).hexdigest()
content = (
    "// Code generated by scripts/update-issue-timezones.py; DO NOT EDIT.\n"
    "// Source: Go 1.27.3 lib/time/zoneinfo.zip (geographic aliases included).\n"
    f"// Bundle SHA-256: {digest}\n\n"
    "package daemon\n\nvar portableIssueTimezones = [...]string{\n"
)
for start in range(0, len(names), 4):
    content += "\t" + " ".join(f'"{name}",' for name in names[start:start + 4]) + "\n"
content += "}\n"
target = Path(__file__).resolve().parent.parent / "internal/daemon/issue_timezones_gen.go"
if args.check:
    if target.read_text() != content:
        raise SystemExit("issue timezone inventory differs; refresh with the pinned Go bundle")
    print(f"issue timezone inventory matches: {len(names)} names, sha256 {digest}")
else:
    target.write_text(content)
